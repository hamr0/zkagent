/**
 * `zk-passport/1` (PRD D25, M1 spec §5 B3): the four-stage zkPassport
 * composition — DSC→CSCA, SOD→DSC, DG1↔SOD integrity, age/disclosure — each an
 * UltraHonk proof verified by shelling out to a pinned `bb` (5.0.0) binary.
 * Tier ceiling 'A' only (tier B/C ZK is Q26). Linkability 'none'.
 *
 * Envelope (`item.data`), every byte string base64:
 *
 *   { stages: {
 *       dsc:       { proof, public_inputs, vk_sha256? },   // public_inputs 64 B
 *       id_data:   { proof, public_inputs, vk_sha256? },   // 64 B
 *       integrity: { proof, public_inputs, vk_sha256? },   // 64 B
 *       age:       { proof, public_inputs, vk_sha256? },   // 256 B (8 Fields)
 *   } }
 *
 * `vk_sha256` (hex) selects among several pinned VKs for a stage when more than
 * one is registered (the DSC circuit variant depends on the document's TBS
 * length); with exactly one VK pinned it may be omitted.
 *
 * Public-input layout (32-byte big-endian Fields, read from the real spike
 * artefacts, `compare/age/standard/src/main.nr`):
 *   dsc / id_data / integrity:  [comm_in, comm_out]
 *   age: [comm_in, current_date, service_scope, service_subscope,
 *         param_commitment, nullifier_type, nullifier, oprf_pk_hash]
 *
 * Bindings (checked from the bytes, then sealed by `bb verify` over the same
 * bytes):
 *   age    — age[1] `current_date` (s) + ctx.maxScanAge >= ctx.now, when set
 *   nonce  — age[3] `service_subscope` == subscopeFromNonce(ctx.nonce)
 *   claim  — age[4] `param_commitment` == pinned Poseidon2 table entry for
 *            config.threshold (`zk-passport-params.json`, generated by
 *            spikes/m1-zk/params-table with the vendored circuit library)
 *   scope  — age[2] `service_scope` == scopeField(ctx.scopeDomain)
 *   chain  — dsc.comm_out == id_data.comm_in, id_data.comm_out ==
 *            integrity.comm_in, integrity.comm_out == age.comm_in
 *
 * Registry rule `zk-passport/1`: subscopeFromNonce(nonce) = the first 31 bytes
 * of sha256(utf8 nonce), big-endian, as a Field (< 2^248, so always below the
 * BN254 modulus). scopeField(domain) is the same construction over the domain
 * string — which is exactly `getScopeHash()` in `@zkpassport/utils` 0.37.4,
 * reproduced here rather than imported (zero deps).
 */
import { createHash } from 'node:crypto';
import { execFile, execFileSync } from 'node:child_process';
import { mkdtemp, rm, writeFile, readFileSync } from 'node:fs';
import { promises as fsp } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { promisify } from 'node:util';

const execFileP = promisify(execFile);
const BB_VERSION = '5.0.0';
const STAGES = ['dsc', 'id_data', 'integrity', 'age'];
const PI_LEN = Object.freeze({ dsc: 64, id_data: 64, integrity: 64, age: 256 });
const PARAMS = JSON.parse(readFileSync(new URL('./zk-passport-params.json', import.meta.url), 'utf8'));
const FUTURE_SKEW_MS = 300_000;

/** sha256(utf8)[0:31] as a 32-byte big-endian Field (leading zero byte). */
function hash31(str) {
  return Buffer.concat([Buffer.alloc(1), createHash('sha256').update(str, 'utf8').digest().subarray(0, 31)]);
}
export function subscopeFromNonce(nonce) { return hash31(nonce); }
export function scopeField(scopeDomain) { return hash31(scopeDomain); }

/** The pinned param_commitment for a threshold, as 32 bytes, or undefined. */
export function paramCommitment(threshold) {
  const hex = PARAMS.commitments[String(threshold)];
  return hex ? Buffer.from(hex.slice(2), 'hex') : undefined;
}

function invalid(reason) { return { ok: true, valid: false, reason }; }

/**
 * @param {{
 *   bbPath: string,
 *   vks: {dsc: string|string[], id_data: string|string[], integrity: string|string[], age: string|string[]},
 *   threshold: number,
 * }} opts
 */
export function zkPassport({ bbPath, vks, threshold } = {}) {
  if (typeof bbPath !== 'string' || bbPath.length === 0) {
    throw new TypeError('zk-passport/1: registration needs an explicit bbPath (bb is never searched on PATH)');
  }
  let version;
  try {
    version = execFileSync(bbPath, ['--version'], { encoding: 'utf8', timeout: 10_000 }).trim();
  } catch (e) {
    throw new TypeError(`zk-passport/1: cannot run bb at ${bbPath}: ${e.message}`);
  }
  if (version !== BB_VERSION) {
    throw new TypeError(`zk-passport/1: bb at ${bbPath} reports version "${version}", pinned ${BB_VERSION}`);
  }
  if (!Number.isInteger(threshold) || !paramCommitment(threshold)) {
    throw new TypeError(`zk-passport/1: threshold ${threshold} has no pinned param_commitment (table covers 0..100)`);
  }
  const expectedParam = paramCommitment(threshold);

  // Pin every VK by path at registration; index by sha256 so an envelope can
  // name which pinned VK a stage was proved against.
  const pinned = {};
  if (!vks || typeof vks !== 'object') throw new TypeError('zk-passport/1: registration needs vks per stage');
  for (const st of STAGES) {
    const list = Array.isArray(vks[st]) ? vks[st] : [vks[st]];
    if (list.length === 0 || list.some((p) => typeof p !== 'string' || p.length === 0)) {
      throw new TypeError(`zk-passport/1: vks.${st} must be a path or a non-empty list of paths`);
    }
    pinned[st] = new Map();
    for (const p of list) {
      let bytes;
      try { bytes = readFileSync(p); } catch (e) { throw new TypeError(`zk-passport/1: cannot read vk ${p}: ${e.message}`); }
      pinned[st].set(createHash('sha256').update(bytes).digest('hex'), p);
    }
  }

  function selectVk(st, stage) {
    const map = pinned[st];
    if (stage.vk_sha256 !== undefined) {
      if (typeof stage.vk_sha256 !== 'string') return undefined;
      return map.get(stage.vk_sha256.toLowerCase());
    }
    return map.size === 1 ? map.values().next().value : undefined;
  }

  function decodeStage(stages, st) {
    const s = stages[st];
    if (!s || typeof s !== 'object' || typeof s.proof !== 'string' || typeof s.public_inputs !== 'string') return null;
    const proof = Buffer.from(s.proof, 'base64');
    const pi = Buffer.from(s.public_inputs, 'base64');
    if (proof.length === 0 || pi.length !== PI_LEN[st]) return null;
    return { proof, pi, vk: selectVk(st, s) };
  }

  return Object.freeze({
    binds: Object.freeze({ nonce: true, claim: true, scope: true }),
    linkability: 'none',
    tierCeiling: 'A',
    async verify(item, ctx) {
      const stages = item?.data?.stages;
      if (!stages || typeof stages !== 'object') return invalid('zk_envelope_malformed');
      const d = {};
      for (const st of STAGES) {
        d[st] = decodeStage(stages, st);
        if (!d[st]) return invalid('zk_envelope_malformed');
        if (!d[st].vk) return invalid('zk_unknown_circuit');
      }
      const field = (st, i) => d[st].pi.subarray(i * 32, (i + 1) * 32);

      // --- bindings from the bytes (cheap, before any bb call) --------------
      if (!field('dsc', 1).equals(field('id_data', 0))
        || !field('id_data', 1).equals(field('integrity', 0))
        || !field('integrity', 1).equals(field('age', 0))) return invalid('zk_chain_broken');
      if (typeof ctx?.nonce !== 'string' || !field('age', 3).equals(subscopeFromNonce(ctx.nonce))) return invalid('zk_nonce_mismatch');
      if (!field('age', 4).equals(expectedParam)) return invalid('zk_threshold_mismatch');
      if (typeof ctx?.scopeDomain !== 'string' || !field('age', 2).equals(scopeField(ctx.scopeDomain))) return invalid('zk_scope_mismatch');
      const currentDate = field('age', 1);
      if (!currentDate.subarray(0, 24).equals(Buffer.alloc(24))) return invalid('zk_date_malformed');
      const currentDateMs = Number(currentDate.readBigUInt64BE(24)) * 1000;
      if (Number.isFinite(ctx?.now) && currentDateMs > ctx.now + FUTURE_SKEW_MS) return invalid('zk_date_in_future');
      // D20 max_scan_age: the proof is dated by its own current_date; a scan
      // older than the challenge allows is refused (ctx.maxScanAge null = unlimited).
      const maxScanAge = ctx?.maxScanAge ?? null;
      if (maxScanAge !== null && Number.isFinite(ctx?.now) && currentDateMs + maxScanAge < ctx.now) {
        return invalid('zk_scan_too_old');
      }

      // --- the proofs themselves ---------------------------------------------
      let dir;
      try {
        dir = await fsp.mkdtemp(join(tmpdir(), 'chiproof-zk-'));
        for (const st of STAGES) {
          const proofPath = join(dir, `${st}.proof`);
          const piPath = join(dir, `${st}.public_inputs`);
          await fsp.writeFile(proofPath, d[st].proof);
          await fsp.writeFile(piPath, d[st].pi);
          try {
            await execFileP(bbPath, ['verify', '-k', d[st].vk, '-p', proofPath, '-i', piPath], { timeout: 60_000 });
          } catch (e) {
            // A non-zero exit is bb's verdict (a real no); anything else --
            // ENOENT, a signal, a timeout -- is the verifier being broken.
            if (typeof e.code === 'number' && e.code > 0 && !e.killed) {
              const detail = String(e.stderr ?? '').split('\n').map((l) => l.trim())
                .find((l) => /fail|error|invalid/i.test(l))?.slice(0, 200);
              return { ok: true, valid: false, reason: 'zk_proof_invalid', stage: st, detail };
            }
            return { ok: false, valid: null, reason: 'zk_bb_unavailable' };
          }
        }
      } catch {
        return { ok: false, valid: null, reason: 'zk_bb_unavailable' };
      } finally {
        if (dir) await fsp.rm(dir, { recursive: true, force: true }).catch(() => {});
      }
      return { ok: true, valid: true, reason: 'zk_verified' };
    },
  });
}
